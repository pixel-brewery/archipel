import type * as DMMF from '@prisma/dmmf';
import { describe, expect, it } from 'vitest';
import type { IJsonSchemaGeneratorConfig } from '../config/IJsonSchemaGeneratorConfig.js';
import { JsonSchemaRenderer } from './JsonSchemaRenderer.js';

/**
 * Creates a minimal DMMF.Field with Prisma 7 required properties.
 */
const field = (overrides: Partial<DMMF.Field> & Pick<DMMF.Field, 'name' | 'kind' | 'type'>): DMMF.Field =>
    ({
        isRequired: true,
        isList: false,
        isUnique: false,
        isId: false,
        isReadOnly: false,
        hasDefaultValue: false,
        ...overrides,
    }) as DMMF.Field;

/**
 * Creates a minimal DMMF.Model with Prisma 7 required properties.
 */
const model = (overrides: Partial<DMMF.Model> & Pick<DMMF.Model, 'name' | 'fields'>): DMMF.Model =>
    ({
        dbName: null,
        schema: null,
        uniqueFields: [],
        uniqueIndexes: [],
        primaryKey: null,
        ...overrides,
    }) as DMMF.Model;

/**
 * Creates a minimal DMMF.Datamodel with Prisma 7 required properties.
 */
const datamodel = (overrides: Partial<DMMF.Datamodel>): DMMF.Datamodel =>
    ({
        models: [],
        enums: [],
        types: [],
        indexes: [],
        ...overrides,
    }) as DMMF.Datamodel;

/**
 * Creates a minimal DMMF.EnumValue with Prisma 7 required properties.
 */
const enumValue = (name: string): DMMF.EnumValue =>
    ({
        name,
        dbName: null,
    }) as DMMF.EnumValue;

describe('JsonSchemaRenderer', () => {
    const baseConfig: IJsonSchemaGeneratorConfig = {
        fileName: 'manifest.json',
        schemaFileSuffix: '.schema.json',
        schemaVersion: 'https://json-schema.org/schema',
        emitGeneratorComment: true,
        modelNamingConvention: {
            prefix: '',
            suffix: '',
        },
        enumNamingConvention: {
            prefix: '',
            suffix: '',
        },
    };

    it('renders enums and models into discrete schema files with manifest references', () => {
        const dm = datamodel({
            enums: [
                {
                    name: 'Role',
                    documentation: 'Represents user roles.',
                    values: [enumValue('ADMIN'), enumValue('USER')],
                } as DMMF.DatamodelEnum,
            ],
            models: [
                model({
                    name: 'User',
                    documentation: 'Represents an authenticated account.',
                    fields: [
                        field({ name: 'id', kind: 'scalar', type: 'String', isId: true, documentation: 'Primary identifier.' }),
                        field({ name: 'name', kind: 'scalar', type: 'String', isRequired: false }),
                        field({ name: 'roles', kind: 'enum', type: 'Role', isList: true, documentation: 'Assigned roles.' }),
                        field({
                            name: 'profile',
                            kind: 'object',
                            type: 'Profile',
                            isRequired: false,
                            documentation: 'Linked profile record.',
                        }),
                    ],
                }),
                model({
                    name: 'Profile',
                    fields: [field({ name: 'id', kind: 'scalar', type: 'Int', isId: true }), field({ name: 'user', kind: 'object', type: 'User' })],
                }),
            ],
        });

        const renderer = new JsonSchemaRenderer(baseConfig);
        const output = renderer.render(dm);

        expect(output.primaryFile.fileName).toBe('manifest.json');
        const manifest = JSON.parse(output.primaryFile.content) as Record<string, unknown>;
        expect(manifest).toEqual({
            $schema: 'https://json-schema.org/schema',
            $comment: 'Generated by prisma-generator-json-schema.',
            models: {
                Profile: { $ref: './Profile.schema.json' },
                User: { $ref: './User.schema.json' },
            },
            enums: {
                Role: { $ref: './Role.schema.json' },
            },
        });

        expect(output.supportingFiles).toHaveLength(3);
        const [enumFile, userFile, profileFile] = output.supportingFiles;
        expect(enumFile.fileName).toBe('Role.schema.json');
        expect(JSON.parse(enumFile.content)).toEqual({
            $schema: 'https://json-schema.org/schema',
            $id: 'Role',
            title: 'Role',
            type: 'string',
            enum: ['ADMIN', 'USER'],
            description: 'Represents user roles.',
            $comment: 'Generated by prisma-generator-json-schema.',
        });

        expect(userFile.fileName).toBe('User.schema.json');
        expect(JSON.parse(userFile.content)).toEqual({
            $schema: 'https://json-schema.org/schema',
            $id: 'User',
            title: 'User',
            description: 'Represents an authenticated account.',
            type: 'object',
            additionalProperties: false,
            properties: {
                id: {
                    type: 'string',
                    description: 'Primary identifier.',
                },
                name: {
                    type: ['string', 'null'],
                },
                roles: {
                    type: 'array',
                    items: { $ref: './Role.schema.json' },
                    description: 'Assigned roles.',
                },
                profile: {
                    anyOf: [{ $ref: './Profile.schema.json' }, { type: 'null' }],
                    description: 'Linked profile record.',
                },
            },
            required: ['id', 'roles'],
            $comment: 'Generated by prisma-generator-json-schema.',
        });

        expect(profileFile.fileName).toBe('Profile.schema.json');
        expect(JSON.parse(profileFile.content)).toEqual({
            $schema: 'https://json-schema.org/schema',
            $id: 'Profile',
            title: 'Profile',
            type: 'object',
            additionalProperties: false,
            properties: {
                id: {
                    type: 'integer',
                },
                user: {
                    $ref: './User.schema.json',
                },
            },
            required: ['id', 'user'],
            $comment: 'Generated by prisma-generator-json-schema.',
        });
    });

    it('omits generator comments when disabled', () => {
        const renderer = new JsonSchemaRenderer({
            ...baseConfig,
            emitGeneratorComment: false,
        });

        const dm = datamodel({ enums: [], models: [] });
        const output = renderer.render(dm);
        expect(JSON.parse(output.primaryFile.content)).toEqual({
            $schema: 'https://json-schema.org/schema',
            models: {},
            enums: {},
        });
    });

    it('applies naming convention transformations to generated file names', () => {
        const renderer = new JsonSchemaRenderer({
            ...baseConfig,
            schemaFileSuffix: '.json',
            modelNamingConvention: {
                prefix: 'custom-',
                suffix: '-schema',
                replace: {
                    regex: '([A-Z])',
                    value: '-$1',
                },
            },
            enumNamingConvention: {
                prefix: 'enum-',
                suffix: '',
                replace: {
                    regex: 'Role',
                    value: 'permission',
                },
            },
        });

        const dm = datamodel({
            enums: [{ name: 'Role', values: [] } as unknown as DMMF.DatamodelEnum],
            models: [model({ name: 'ApiClient', fields: [] })],
        });

        const output = renderer.render(dm);
        expect(output.supportingFiles.map((file) => file.fileName)).toEqual(['enum-permission.json', 'custom--Api-Client-schema.json']);

        const manifest = JSON.parse(output.primaryFile.content) as Record<string, unknown>;
        expect(manifest).toMatchObject({
            models: {
                ApiClient: { $ref: './custom--Api-Client-schema.json' },
            },
            enums: {
                Role: { $ref: './enum-permission.json' },
            },
        });
    });
});
