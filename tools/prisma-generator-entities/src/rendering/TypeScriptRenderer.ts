import type * as DMMF from '@prisma/dmmf';
import { CodeBlockWriter, IndentationText, NewLineKind, Project, QuoteKind, type SourceFile } from 'ts-morph';
import type { IEntityGeneratorConfig } from '../config/IEntityGeneratorConfig.js';
import { TypeMapper } from '../utils/TypeMapper.js';
import type { IRenderedOutput, IRenderedSourceFile } from './IRenderedSourceFile.js';

/**
 * Creates TypeScript source files representing Prisma models as immutable interfaces using ts-morph.
 */
export class TypeScriptRenderer {
    // #region Fields

    private readonly _config: IEntityGeneratorConfig;
    private readonly _typeMapper: TypeMapper;

    // #endregion

    // #region Ctor

    public constructor(config: IEntityGeneratorConfig) {
        this._config = config;
        this._typeMapper = new TypeMapper(config.useReadonlyArray, config.modelNamingConventionPrefix, config.modelNamingConventionSuffix);
    }

    // #endregion

    // #region Methods

    /**
     * Renders the provided Prisma datamodel into TypeScript source files.
     *
     * @param datamodel Prisma data model meta format representation
     */
    public render(datamodel: DMMF.Datamodel): IRenderedOutput {
        const project = this.createProject();
        const header = this.renderHeader();
        const supportingFiles: IRenderedSourceFile[] = [];

        const enumsToGenerate = this._config.generateEnums ? datamodel.enums : [];
        const modelsToGenerate = this._config.generateModels ? datamodel.models : [];

        // Render each enum into its own file
        for (const enumeration of enumsToGenerate) {
            supportingFiles.push(this.renderEnumFile(project, enumeration, header));
        }

        for (const model of modelsToGenerate) {
            supportingFiles.push(this.renderModelFile(project, model, header));
        }

        const indexSourceFile = this.renderIndexFile(project, header, enumsToGenerate, modelsToGenerate);

        return {
            primaryFile: {
                fileName: this._config.fileName,
                content: this.finalizeSourceFileWithHeader(indexSourceFile, header),
            },
            supportingFiles,
        };
    }

    private createProject(): Project {
        return new Project({
            useInMemoryFileSystem: true,
            manipulationSettings: {
                indentationText: IndentationText.FourSpaces,
                quoteKind: QuoteKind.Single,
                useTrailingCommas: false,
                newLineKind: NewLineKind.LineFeed,
            },
        });
    }

    private renderHeader(): string {
        return [
            '// ------------------------------------------------------------------------------',
            '// <auto-generated>',
            '//     This code was generated by a tool.',
            '//     Changes to this file may cause incorrect behavior and will be lost if',
            '//     the code is regenerated.',
            '// </auto-generated>',
            '// ------------------------------------------------------------------------------',
        ].join('\n');
    }

    private renderEnumFile(project: Project, enumeration: DMMF.DatamodelEnum, header: string | null): IRenderedSourceFile {
        const fileName = this.buildEnumFileName(enumeration.name);
        const sourceFile = project.createSourceFile(fileName, '', { overwrite: true });

        sourceFile.addStatements((writer) => {
            if (enumeration.documentation) {
                this.writeDocComment(writer, enumeration.documentation);
            }

            writer.writeLine(`export const ${enumeration.name} = {`);
            writer.indent(() => {
                for (const enumValue of enumeration.values) {
                    // if (enumValue.documentation) {
                    //     this._writeDocComment(writer, enumValue.documentation);
                    // }

                    writer.writeLine(`${enumValue.name}: '${enumValue.name}',`);
                }
            });
            writer.writeLine('} as const;');
            writer.writeLine(`export type ${enumeration.name} = typeof ${enumeration.name}[keyof typeof ${enumeration.name}];`);
        });

        return {
            fileName,
            content: this.finalizeSourceFileWithHeader(sourceFile, header),
        };
    }

    private renderModelFile(project: Project, model: DMMF.Model, header: string | null): IRenderedSourceFile {
        const fileName = this.buildModelFileName(model.name);
        const sourceFile = project.createSourceFile(fileName, '', { overwrite: true });
        this.addModelImports(sourceFile, model);
        this.addModelInterface(sourceFile, model);

        return {
            fileName,
            content: this.finalizeSourceFileWithHeader(sourceFile, header),
        };
    }

    private renderIndexFile(project: Project, header: string | null, enums: ReadonlyArray<DMMF.DatamodelEnum>, models: ReadonlyArray<DMMF.Model>): SourceFile {
        const sourceFile = project.createSourceFile(this._config.fileName, '', { overwrite: true });

        const useNamespace = this._config.namespaceName.trim().length > 0;
        if (useNamespace) {
            this.renderNamespacedIndexFile(sourceFile, enums, models);
        } else {
            this.renderFlatIndexFile(sourceFile, enums, models);
        }

        return sourceFile;
    }

    private renderFlatIndexFile(sourceFile: SourceFile, enums: ReadonlyArray<DMMF.DatamodelEnum>, models: ReadonlyArray<DMMF.Model>): void {
        let hasExports = false;

        if (enums.length > 0) {
            const sortedEnums = [...enums].sort((left, right) => left.name.localeCompare(right.name));
            for (const enumeration of sortedEnums) {
                sourceFile.addExportDeclaration({
                    moduleSpecifier: `./${this.normalizeImportPath(this.buildEnumFileName(enumeration.name))}`,
                });
            }
            hasExports = true;
        }

        const sortedModels = [...models].sort((left, right) => left.name.localeCompare(right.name));

        for (const model of sortedModels) {
            const interfaceName = `${this._config.modelNamingConventionPrefix}${model.name}${this._config.modelNamingConventionSuffix}`;
            sourceFile.addExportDeclaration({
                isTypeOnly: true,
                moduleSpecifier: `./${this.normalizeImportPath(this.buildModelFileName(model.name))}`,
                namedExports: [interfaceName],
            });
            hasExports = true;
        }

        if (!hasExports) {
            const reasons: string[] = [];
            if (!this._config.generateModels) {
                reasons.push('generateModels is disabled');
            }
            if (!this._config.generateEnums) {
                reasons.push('generateEnums is disabled');
            }
            const reasonText = reasons.length > 0 ? ` (${reasons.join(', ')})` : '';
            sourceFile.addStatements(`// No entities generated${reasonText}.`);
        }
    }

    private renderNamespacedIndexFile(sourceFile: SourceFile, enums: ReadonlyArray<DMMF.DatamodelEnum>, models: ReadonlyArray<DMMF.Model>): void {
        const sortedEnums = [...enums].sort((left, right) => left.name.localeCompare(right.name));
        const sortedModels = [...models].sort((left, right) => left.name.localeCompare(right.name));

        // Collect all exports for namespace
        const enumExports: string[] = [];
        const modelExports: string[] = [];
        let hasExports = false;

        // Import and prepare enums
        if (this._config.generateEnums) {
            for (const enumeration of sortedEnums) {
                const importPath = `./${this.normalizeImportPath(this.buildEnumFileName(enumeration.name))}`;
                sourceFile.addImportDeclaration({
                    moduleSpecifier: importPath,
                    namespaceImport: `_${enumeration.name}`,
                });
                enumExports.push(`export import ${enumeration.name} = _${enumeration.name}.${enumeration.name};`);
                enumExports.push(`export type ${enumeration.name} = _${enumeration.name}.${enumeration.name};`);
                hasExports = true;
            }
        }

        // Import and prepare models
        if (this._config.generateModels) {
            for (const model of sortedModels) {
                const interfaceName = `${this._config.modelNamingConventionPrefix}${model.name}${this._config.modelNamingConventionSuffix}`;
                const importPath = `./${this.normalizeImportPath(this.buildModelFileName(model.name))}`;
                sourceFile.addImportDeclaration({
                    isTypeOnly: true,
                    moduleSpecifier: importPath,
                    namedImports: [interfaceName],
                });
                modelExports.push(`export type { ${interfaceName} };`);
                hasExports = true;
            }
        }

        if (!hasExports) {
            const reasons: string[] = [];
            if (!this._config.generateModels) {
                reasons.push('generateModels is disabled');
            }
            if (!this._config.generateEnums) {
                reasons.push('generateEnums is disabled');
            }
            const reasonText = reasons.length > 0 ? ` (${reasons.join(', ')})` : '';
            sourceFile.addStatements(`// No entities generated${reasonText}.`);
            return;
        }

        // Create namespace with single blank line before it
        sourceFile.addStatements((writer) => {
            writer.newLine();
            writer.writeLine(`export declare namespace ${this._config.namespaceName} {`);
            writer.indent(() => {
                // Export enums
                for (const enumExport of enumExports) {
                    writer.writeLine(enumExport);
                }

                if (enumExports.length > 0 && modelExports.length > 0) {
                    writer.newLine();
                }

                // Export models
                for (const modelExport of modelExports) {
                    writer.writeLine(modelExport);
                }
            });
            writer.writeLine('}');
        });
    }

    private addModelImports(sourceFile: SourceFile, model: DMMF.Model): void {
        const enumTypes = new Set<string>();
        const relationTypes = new Set<string>();

        for (const field of model.fields) {
            if (field.kind === 'enum') {
                enumTypes.add(field.type);
            }

            if (field.kind === 'object' && field.type !== model.name) {
                relationTypes.add(field.type);
            }
        }

        if (enumTypes.size > 0) {
            const sortedEnumTypes = [...enumTypes].sort((left, right) => left.localeCompare(right));

            // If generateEnums is disabled and usePrismaEnumsWhenDisabled is enabled,
            // import enums from @prisma/client instead of local files
            if (!this._config.generateEnums && this._config.usePrismaEnumsWhenDisabled) {
                sourceFile.addImportDeclaration({
                    isTypeOnly: true,
                    moduleSpecifier: this._config.prismaClientImportPath,
                    namedImports: sortedEnumTypes,
                });
            } else if (this._config.generateEnums) {
                // Import from generated enum files (legacy behavior)
                for (const enumType of sortedEnumTypes) {
                    sourceFile.addImportDeclaration({
                        isTypeOnly: true,
                        moduleSpecifier: `./${this.normalizeImportPath(this.buildEnumFileName(enumType))}`,
                        namedImports: [enumType],
                    });
                }
            }
            // If generateEnums is false and usePrismaEnumsWhenDisabled is false,
            // don't add any enum imports (legacy behavior - will cause type errors)
        }

        const sortedRelationTypes = [...relationTypes].sort((left, right) => left.localeCompare(right));

        for (const relationType of sortedRelationTypes) {
            sourceFile.addImportDeclaration({
                isTypeOnly: true,
                moduleSpecifier: `./${this.normalizeImportPath(this.buildModelFileName(relationType))}`,
                namedImports: [`${this._config.modelNamingConventionPrefix}${relationType}${this._config.modelNamingConventionSuffix}`],
            });
        }
    }

    private addModelInterface(sourceFile: SourceFile, model: DMMF.Model): void {
        const hasExistingStatements = sourceFile.getStatements().length > 0;
        sourceFile.addStatements((writer) => {
            if (hasExistingStatements) {
                writer.newLine();
            }

            if (model.documentation) {
                this.writeDocComment(writer, model.documentation);
            }

            writer.writeLine(`export interface ${this._config.modelNamingConventionPrefix}${model.name}${this._config.modelNamingConventionSuffix} {`);
            writer.indent(() => {
                for (const field of model.fields) {
                    if (field.documentation) {
                        this.writeDocComment(writer, field.documentation);
                    }

                    const isRequired = field.isRequired;
                    const isList = field.isList;
                    const isRelation =
                        (Array.isArray(field.relationFromFields) && field.relationFromFields.length > 0) ||
                        (Array.isArray(field.relationToFields) && field.relationToFields.length > 0);
                    const isOptional = !isRequired || isRelation || isList ? true : false;
                    const listAwareType = this._typeMapper.applyListModifier(this._typeMapper.resolve(field), isList);
                    const nullAwareType = !field.isRequired ? `${listAwareType} | null` : listAwareType;

                    writer.writeLine(`readonly ${this.formatPropertyName(field.name)}${isOptional ? '?' : ''}: ${nullAwareType};`);
                }
            });
            writer.writeLine('}');
        });
    }

    private applyHeader(sourceFile: SourceFile, header: string | null): void {
        if (!header) {
            return;
        }

        sourceFile.addStatements((writer) => {
            for (const line of header.split('\n')) {
                writer.writeLine(line);
            }
            writer.blankLine();
        });
    }

    private writeDocComment(writer: CodeBlockWriter, documentation: string): void {
        const sanitizedLines = documentation.split('\n').map((line) => line.trim());

        writer.writeLine('/**');
        for (const line of sanitizedLines) {
            if (line.length > 0) {
                writer.writeLine(` * ${line}`);
            } else {
                writer.writeLine(' *');
            }
        }
        writer.writeLine(' */');
    }

    private finalizeSourceFile(sourceFile: SourceFile): string {
        sourceFile.formatText({ ensureNewLineAtEndOfFile: true });
        const content = sourceFile.getFullText();
        const normalized = content.replace(/\n+$/u, '\n');

        return normalized.endsWith('\n') ? normalized : `${normalized}\n`;
    }

    private finalizeSourceFileWithHeader(sourceFile: SourceFile, header: string | null): string {
        sourceFile.formatText({ ensureNewLineAtEndOfFile: true });
        let content = sourceFile.getFullText();

        if (header) {
            content = `${header}\n\n${content}`;
        }

        const normalized = content.replace(/\n+$/u, '\n');
        return normalized.endsWith('\n') ? normalized : `${normalized}\n`;
    }

    private buildModelFileName(modelName: string): string {
        const normalizedName = this.applyNamingConvention(
            modelName,
            this._config.modelNamingConventionPrefix,
            this._config.modelNamingConventionSuffix,
            this._config.modelNamingConventionReplaceRegex,
            this._config.modelNamingConventionReplaceValue,
        );
        return `${normalizedName}${this._config.entityFileSuffix}`;
    }

    private buildEnumFileName(enumName: string): string {
        const normalizedName = this.applyNamingConvention(
            enumName,
            this._config.enumNamingConventionPrefix,
            this._config.enumNamingConventionSuffix,
            this._config.enumNamingConventionReplaceRegex,
            this._config.enumNamingConventionReplaceValue,
        );
        const baseName = normalizedName.length > 0 ? normalizedName : enumName;

        return baseName.endsWith('.ts') ? baseName : `${baseName}.ts`;
    }

    private applyNamingConvention(name: string, prefix: string, suffix: string, replaceRegex?: string, replaceValue?: string): string {
        let normalizedName = name;

        if (replaceRegex && replaceRegex.length > 0 && replaceValue !== undefined) {
            try {
                const pattern = new RegExp(replaceRegex, 'gu');
                normalizedName = normalizedName.replace(pattern, replaceValue);
            } catch {
                normalizedName = normalizedName.split(replaceRegex).join(replaceValue);
            }
        }

        return `${prefix}${normalizedName}${suffix}`;
    }

    private normalizeImportPath(fileName: string): string {
        return fileName.replace(/\.ts$/u, '.js');
    }

    private formatPropertyName(name: string): string {
        const identifierPattern = /^[A-Za-z_$][A-Za-z0-9_$]*$/u;
        const reservedKeywords = new Set<string>([
            'break',
            'case',
            'catch',
            'class',
            'const',
            'continue',
            'debugger',
            'default',
            'delete',
            'do',
            'else',
            'enum',
            'export',
            'extends',
            'false',
            'finally',
            'for',
            'function',
            'if',
            'import',
            'in',
            'instanceof',
            'new',
            'null',
            'return',
            'super',
            'switch',
            'this',
            'throw',
            'true',
            'try',
            'typeof',
            'var',
            'void',
            'while',
            'with',
            'implements',
            'interface',
            'let',
            'package',
            'private',
            'protected',
            'public',
            'static',
            'yield',
        ]);

        if (identifierPattern.test(name) && !reservedKeywords.has(name)) {
            return name;
        }

        const escapedName = name.replace(/\\/gu, '\\\\').replace(/'/gu, "\\'");
        return `['${escapedName}']`;
    }

    // #endregion
}
