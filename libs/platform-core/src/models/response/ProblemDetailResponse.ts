// #region Imports

import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';

// #endregion

/**
 * OpenAPI schema class representing a Problem Detail response as per RFC 9457.
 *
 * This class is used exclusively for Swagger / OpenAPI documentation. It is
 * **not** instantiated at runtime — the actual response body is produced by
 * {@link ProblemDetailExceptionFilter}.
 *
 * The static {@link MEDIA_TYPE} property signals to the `@Api` decorator
 * that this response schema must be served under `application/problem+json`
 * instead of the default `application/json`.
 *
 * Usage in controllers:
 * ```typescript
 * @Api({
 *     responses: [
 *         { status: HttpStatus.NOT_FOUND, description: 'User not found.', type: ProblemDetailResponse },
 *     ]
 * })
 * ```
 *
 * @public
 */
export class ProblemDetailResponse {
    // #region Fields

    /**
     * The media type for Problem Detail responses as per RFC 9457.
     *
     * This static property is consumed by the `@Api` decorator to override the
     * default `application/json` content type when this class is used as a
     * response `type`.
     *
     * @public
     */
    public static readonly MEDIA_TYPE = 'application/problem+json';

    // #endregion

    // #region Properties

    @ApiProperty({
        description: 'A URI reference (RFC 3986) that identifies the problem type.',
        example: 'https://httpstatuses.com/404',
    })
    public type!: string;

    @ApiProperty({
        description: 'A short, human-readable summary of the problem type.',
        example: 'Not Found',
    })
    public title!: string;

    @ApiProperty({
        description: 'The HTTP status code generated by the origin server for this occurrence of the problem.',
        example: 404,
    })
    public status!: number;

    @ApiProperty({
        description: 'A human-readable explanation specific to this occurrence of the problem.',
        example: 'The requested resource could not be found.',
    })
    public detail!: string;

    @ApiPropertyOptional({
        description: 'A URI reference that identifies the specific occurrence of the problem.',
        example: '/api/v1/users/42',
    })
    public instance?: string;

    @ApiPropertyOptional({
        description: 'A machine-readable error code identifying the specific domain error.',
        example: 'USER_NOT_FOUND',
    })
    public code?: string;

    // #endregion
}
