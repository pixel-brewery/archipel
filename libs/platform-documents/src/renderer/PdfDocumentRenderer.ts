import { Injectable, Logger } from '@nestjs/common';
import { PageSizes, PDFDocument, PDFFont, PDFPage, rgb } from 'pdf-lib';
import { DocumentRenderError } from '../errors/DocumentRenderError.js';
import { DocumentValidationError } from '../errors/DocumentValidationError.js';
import { IRenderOptions } from '../interfaces/IRenderOptions.js';
import { DocumentFormat, IRenderResult } from '../types/DocumentTypes.js';
import { DocumentRendererBase } from './abstracts/DocumentRendererBase.js';

/**
 * PDF document renderer using pdf-lib.
 * Supports placeholder overlay and table rendering.
 *
 * @public
 */
@Injectable()
export class PdfDocumentRenderer extends DocumentRendererBase {
    //#region Fields

    private readonly _logger: Logger = new Logger(PdfDocumentRenderer.name);

    //#endregion

    // #region Methods

    /**
     * Supported document formats.
     */
    public get supportedFormats(): ReadonlyArray<DocumentFormat> {
        return ['pdf'];
    }

    /**
     * Render PDF document from template.
     *
     * @public
     * @param options - Render options
     * @returns Render result
     */
    public async render(options: IRenderOptions): Promise<IRenderResult> {
        // Get template buffer from either uploaded buffer or ResourceManager
        let templateBuffer: Buffer;
        const source = options.templateId ? `id=${options.templateId}` : 'buffer';

        if (options.template) {
            // Validate that template is not a string (PDF doesn't support raw XML)
            if (typeof options.template === 'string') {
                throw new DocumentValidationError('PDF renderer does not support raw XML string templates. Use Buffer with PDF content.');
            }
            templateBuffer = options.template;
            this._logger.debug(`source=${source} bytes=${templateBuffer.length}`);
        } else if (options.templateId) {
            const resource = await this._resourceManager.loadAsync(options.templateId);
            templateBuffer = resource.content;
            this._logger.debug(`source=${source} bytes=${templateBuffer.length}`);
        } else {
            throw new DocumentValidationError('Either templateId or templateBuffer must be provided');
        }

        const processedData = await this.preprocessData(options.data);
        this._logger.debug(`dataKeys=${Object.keys(processedData).join(',')}`);

        let pdfDoc: PDFDocument;
        try {
            pdfDoc = await PDFDocument.load(templateBuffer);
        } catch (e: unknown) {
            throw new DocumentRenderError('Failed to load PDF template', e);
        }
        const pages = pdfDoc.getPages();
        const font = await pdfDoc.embedFont('Helvetica');

        this._logger.debug(`loaded pages=${pages.length}`);

        for (const [index, page] of pages.entries()) {
            this._logger.debug(`processing page=${index + 1}/${pages.length}`);
            await this.renderPlaceholders(page, font, processedData);
        }

        const buffer = Buffer.from(await pdfDoc.save());

        this._logger.debug(`generated bytes=${buffer.length}`);

        // PDF renderer doesn't use template parsing, so no placeholders to track
        return {
            buffer: buffer,
            format: 'pdf',
            mimeType: 'application/pdf',
            report: {
                format: 'pdf',
                totalPlaceholders: 0,
                replacedPlaceholders: 0,
                unresolvedPlaceholders: 0,
                success: true,
                dataKeys: Object.keys(processedData),
                placeholders: [],
            },
        };
    }

    /**
     * Create PDF from scratch (no template).
     *
     * @public
     * @param data - Document data
     * @returns Render result
     */
    public async createFromScratch(data: Record<string, unknown>): Promise<IRenderResult> {
        this._logger.debug(`creating fromScratch dataKeys=${Object.keys(data).join(',')}`);

        const pdfDoc = await PDFDocument.create();
        const page = pdfDoc.addPage(PageSizes.A4);
        const font = await pdfDoc.embedFont('Helvetica');
        const processedData = await this.preprocessData(data);

        await this.renderPlaceholders(page, font, processedData);

        const buffer = Buffer.from(await pdfDoc.save());

        this._logger.debug(`created fromScratch bytes=${buffer.length}`);

        // PDF renderer doesn't use template parsing, so no placeholders to track
        return {
            buffer: buffer,
            format: 'pdf',
            mimeType: 'application/pdf',
            report: {
                format: 'pdf',
                totalPlaceholders: 0,
                replacedPlaceholders: 0,
                unresolvedPlaceholders: 0,
                success: true,
                dataKeys: Object.keys(processedData),
                placeholders: [],
            },
        };
    }

    private async renderPlaceholders(page: PDFPage, font: PDFFont, data: Record<string, unknown>): Promise<void> {
        const { height } = page.getSize();
        let yPosition = height - 50;

        for (const [key, value] of Object.entries(data)) {
            if (typeof value === 'string' || typeof value === 'number') {
                page.drawText(`${key}: ${value}`, {
                    x: 50,
                    y: yPosition,
                    size: 12,
                    font,
                    color: rgb(0, 0, 0),
                });
                yPosition -= 20;
            }
        }
    }

    // #endregion
}
